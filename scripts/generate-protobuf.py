#!/usr/bin/env python3
"""Build the pinned Protobuf toolchain and export C# messages for a client project."""
import argparse
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True, help="Client C# output directory")
    parser.add_argument("--force", action="store_true", help="Replace existing Protobuf-generated C# files")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    project = root / "src/GameServer.Protocol/GameServer.Protocol.csproj"
    dotnet_root = os.environ.get("DOTNET_ROOT") or os.environ.get("TCP_DOTNET_ROOT")
    dotnet = shutil.which("dotnet") or (str(Path(dotnet_root) / "dotnet") if dotnet_root else None)
    if not dotnet:
        parser.error("Set DOTNET_ROOT or add dotnet to PATH; see scripts/setup-tcp.sh")
    subprocess.run([dotnet, "build", str(project), "-c", "Release", "-m:1", "--disable-build-servers",
                    "-tl:off", "-p:RestoreLockedMode=true"], cwd=root, check=True)
    assets = json.loads((project.parent / "obj/project.assets.json").read_text())
    package = next(value["path"] for name, value in assets["libraries"].items() if name.startswith("Grpc.Tools/"))
    system = platform.system()
    cpu = platform.machine().lower()
    platforms = {("Linux", "x86_64"): "linux_x64", ("Linux", "aarch64"): "linux_arm64",
                 ("Darwin", "x86_64"): "macosx_x64", ("Darwin", "arm64"): "macosx_x64",
                 ("Windows", "amd64"): "windows_x64", ("Windows", "x86_64"): "windows_x64"}
    target = platforms.get((system, cpu))
    if not target:
        parser.error("This platform is not supported by this export script; normal dotnet build may still work")
    executable = "protoc.exe" if system == "Windows" else "protoc"
    protoc = next((Path(folder) / package / "tools" / target / executable
                   for folder in assets["packageFolders"]
                   if (Path(folder) / package / "tools" / target / executable).is_file()), None)
    if protoc is None:
        parser.error("The pinned Grpc.Tools package has no protoc for this platform")
    output = args.output.resolve()
    with tempfile.TemporaryDirectory(prefix="game-protobuf-") as temporary:
        subprocess.run([str(protoc), "--version"], check=True)
        subprocess.run([str(protoc), "--proto_path=" + str(root / "protos"),
                        "--csharp_out=" + temporary,
                        *map(str, sorted((root / "protos").glob("*.proto")))], check=True)
        # Validate every target before replacing any file, including new business messages.
        planned = []
        for source in sorted(Path(temporary).glob("*.cs")):
            destination = output / source.name
            if destination.is_symlink() or (destination.exists() and not destination.is_file()):
                parser.error(f"Refusing to overwrite non-regular target {destination.name}")
            generated = source.read_bytes()
            if destination.exists():
                if destination.read_bytes() == generated:
                    continue
                if not args.force or not destination.read_text(encoding="utf-8").startswith("// <auto-generated>"):
                    parser.error(f"{destination.name} exists; --force only replaces Protobuf-generated files")
            planned.append((destination, generated))
        output.mkdir(parents=True, exist_ok=True)
        # Stage on the same filesystem for an atomic replacement.
        for destination, generated in planned:
            with tempfile.NamedTemporaryFile(dir=output, delete=False, suffix=".tmp") as staged:
                staged.write(generated)
                staged_path = Path(staged.name)
            try:
                os.replace(staged_path, destination)
            finally:
                staged_path.unlink(missing_ok=True)
    print(f"Exported messages to {output}; client needs Google.Protobuf matching src/Directory.Packages.props")


if __name__ == "__main__":
    main()
