using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using GameServer.Data;

namespace GameServer.SchemaGenerator;

public sealed record GeneratedFile(string Name, string Content, bool Handwritten = false);

public static partial class CodeGenerator
{
    public const string Header = "// <auto-generated by GameServer.SchemaGenerator>";

    public static IReadOnlyList<GeneratedFile> Generate(DatabaseProvider provider,
        IReadOnlyList<TableSchema> tables, string targetNamespace)
    {
        if (!Enum.IsDefined(provider)) throw new SchemaGenerationException("Unsupported database provider.");
        if (string.IsNullOrWhiteSpace(targetNamespace) || targetNamespace.Split('.').Any(p => !NamespacePart().IsMatch(p)))
            throw new SchemaGenerationException("Namespace must consist of C# identifiers separated by dots (use PascalCase).");
        // Escaping every segment also permits namespaces containing C# keywords.
        string ns = string.Join('.', targetNamespace.Split('.').Select(p => "@" + p));
        var files = new List<GeneratedFile>();
        foreach (var table in tables)
        {
            ValidateSqlIdentifier(table.Name);
            if (table.Columns.Count is < 1 or > 4096 || table.Columns.Select(c => c.Name).Distinct(StringComparer.OrdinalIgnoreCase).Count() != table.Columns.Count)
                throw new SchemaGenerationException($"'{table.Name}' has invalid or duplicate columns.");
            var keys = table.Columns.Where(c => c.PrimaryKey).ToArray();
            if (keys.Length != 1 || keys[0].Nullable || keys[0].Computed)
                throw new SchemaGenerationException($"'{table.Name}' requires exactly one non-null, non-computed primary key. Composite/keyless/nullable keys need a custom repository.");
            string stem = Pascal(table.Name), row = stem + "Row", repository = stem + "Repository";
            var properties = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            var body = new StringBuilder();
            string keyType = "";
            foreach (var column in table.Columns)
            {
                ValidateSqlIdentifier(column.Name);
                string property = Pascal(column.Name), type = MapType(provider, column);
                // Object member names would hide inherited members and trigger compiler warnings.
                if (property == row || property is "GetType" or "Equals" or "GetHashCode" or "ToString" or
                    "ReferenceEquals" or "MemberwiseClone" or "Finalize") property += "Value";
                if (!properties.Add(property))
                    throw new SchemaGenerationException($"'{table.Name}' has colliding C# property names. Rename the column or write its mapping manually.");
                if (column.PrimaryKey) keyType = type;
                if (column.Identity && (!column.PrimaryKey || (type != "long" && type != "int")))
                    throw new SchemaGenerationException($"'{table.Name}.{column.Name}' has an identity type unsupported by TableRepository (requires int/long).");
                body.AppendLine($"    [Column(\"{column.Name}\")]");
                if (column.PrimaryKey) body.AppendLine("    [Key]");
                if (column.Identity || column.Computed)
                    body.AppendLine($"    [DatabaseGenerated(DatabaseGeneratedOption.{(column.Identity ? "Identity" : "Computed")})]");
                string initializer = type switch { "string" => " = string.Empty;", "byte[]" => " = [];", _ => "" };
                body.AppendLine($"    public {type} {property} {{ get; set; }}{initializer}").AppendLine();
            }
            string hash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(JsonSerializer.Serialize(new { provider, table }))));
            string header = Header + "\n// Schema SHA256: " + hash + "\n#nullable enable\n";
            files.Add(new(row + ".g.cs", header + $$"""
                using System;
                using System.ComponentModel.DataAnnotations;
                using System.ComponentModel.DataAnnotations.Schema;

                namespace {{ns}};

                [Table("{{table.Name}}")]
                public partial class {{row}}
                {
                {{body.ToString().TrimEnd()}}
                }

                """));
            files.Add(new(repository + ".g.cs", header + $$"""
                using GameServer.Data.Abstractions;
                using GameServer.Data.Tables;

                namespace {{ns}};

                public partial class {{repository}} : TableRepository<{{row}}, {{keyType}}>
                {
                    public {{repository}}(IDatabaseExecutor database) : base(database) { }
                }

                """));
            files.Add(new(repository + ".cs", $$"""
                // Handwritten extension: the generator never overwrites this file.
                namespace {{ns}};

                public partial class {{repository}}
                {
                    // Add table-specific queries here. Use parameterized SqlStatement and QueryRowsAsync.
                }

                """, Handwritten: true));
        }
        if (files.Select(f => f.Name).Distinct(StringComparer.OrdinalIgnoreCase).Count() != files.Count)
            throw new SchemaGenerationException("Selected tables produce colliding C# file names; generate them in separate namespaces/projects.");
        return files.Select(file => file with { Content = file.Content.Replace("\r\n", "\n", StringComparison.Ordinal) }).ToArray();
    }

    public static void ValidateSqlIdentifier(string name)
    {
        if (string.IsNullOrWhiteSpace(name) || !Identifier().IsMatch(name))
            throw new SchemaGenerationException("Table/column names must match [A-Za-z_][A-Za-z0-9_]* for the current table mapper.");
    }

    private static string Pascal(string name)
    {
        string value = string.Concat(name.Split('_', StringSplitOptions.RemoveEmptyEntries)
            .Select(s => char.ToUpperInvariant(s[0]) + s[1..]));
        if (value.Length == 0 || char.IsDigit(value[0]))
            throw new SchemaGenerationException("A table/column name cannot be converted to a C# identifier.");
        return value;
    }

    private static string MapType(DatabaseProvider provider, ColumnSchema column)
    {
        string declared = column.StoreType.Trim().ToLowerInvariant();
        string basic = declared.Split('(', ' ')[0];
        bool unsigned = declared.Contains("unsigned", StringComparison.Ordinal);
        string? type = provider == DatabaseProvider.MySql ? basic switch
        {
            "tinyint" when declared.StartsWith("tinyint(1)", StringComparison.Ordinal) && !unsigned => "bool",
            "bool" or "boolean" => "bool",
            "tinyint" or "smallint" or "mediumint" => "int",
            "int" or "integer" => unsigned ? "long" : "int",
            "bigint" => unsigned ? "ulong" : "long",
            "bit" => "ulong",
            "decimal" or "numeric" => "decimal",
            "float" => "float", "double" or "real" => "double",
            "date" or "datetime" or "timestamp" => "DateTime", "time" => "TimeSpan", "year" => "int",
            "char" or "varchar" or "tinytext" or "text" or "mediumtext" or "longtext" or "json" or "enum" or "set" => "string",
            "binary" or "varbinary" or "tinyblob" or "blob" or "mediumblob" or "longblob" => "byte[]",
            _ => null
        } : basic switch
        {
            "bool" or "boolean" => "bool",
            "tinyint" or "smallint" or "mediumint" or "int" or "integer" or "bigint" or "int2" or "int8" or "unsigned" => "long",
            "float" or "double" or "real" => "double",
            "decimal" or "numeric" => "decimal",
            "date" or "datetime" or "timestamp" => "DateTime",
            "char" or "varchar" or "nchar" or "nvarchar" or "text" or "clob" or "json" => "string",
            "blob" => "byte[]",
            _ => null
        };
        if (type == null)
            throw new SchemaGenerationException($"Column '{column.Name}' has an unsupported declared type; write its mapping manually.");
        return type + (column.Nullable ? "?" : "");
    }

    [GeneratedRegex(@"\A[A-Za-z_][A-Za-z0-9_]*\z")] private static partial Regex Identifier();
    [GeneratedRegex(@"\A[A-Za-z_][A-Za-z0-9_]*\z")] private static partial Regex NamespacePart();
}
